"""Write manuscript/numbers.tex: every review-level number used in the text, computed
from the data files, so the manuscript never carries a stale hand-typed count.
Run after apply_scope_b.py, build_synthesis_set.py, venue_audit.py, drm_evidence.py."""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "data"


def fmt(n):
    return f"{int(n):,}"


def main():
    pr = json.load(open(D / "prisma_counts.json"))
    ms = json.load(open(D / "evidence_map_stats.json"))
    sb = json.load(open(D / "priority_synthesis_B_summary.json"))
    syn = pd.read_csv(D / "synthesis_set.csv", keep_default_na=False)
    va = pd.read_csv(D / "venue_audit" / "venue_audit.csv", keep_default_na=False)
    ft = set(pd.read_csv(D / "extraction_ft.csv", keep_default_na=False).record_id)
    syn["read_full"] = syn.record_id.isin(ft)
    elig = pd.read_csv(D / "synthesis_eligible.csv", keep_default_na=False)
    xv = pd.read_csv(D / "extraction_ft_verification.csv", keep_default_na=False)
    assert (xv.quote_on_page == "yes").all() and xv.numbers_supported.str.startswith("yes").all(), "extraction check failed"
    pri = va[va.group == "priority study"]
    m = {
        "nHits": fmt(pr["identified_total_hits"]),
        "nScreened": fmt(pr["records_screened"]),
        "nEligibleMain": "1,644",
        "nDepth": "16",
        "nMap": fmt(ms["n"]),
        "nMapDet": fmt(ms["det_n"]),
        "nMapDD": fmt(ms["dd_n"]),
        "nMapField": fmt(ms["field_all"]),
        "nMapDetField": fmt(ms["det_n"] and ms["field_det"]),
        "pctMapDetField": f"{100*ms['field_det']/ms['det_n']:.1f}",
        "nMapDetMonthly": fmt(ms["det_M"]),
        "pctMapDetMonthly": f"{100*ms['det_M']/ms['det_n']:.1f}",
        "nMapDetMonthlyReal": fmt(ms["det_M_R"]),
        "nMapDDReal": fmt(ms["dd_LB"].get("R", 0)),
        "pctMapDDReal": f"{100*ms['dd_LB'].get('R',0)/ms['dd_n']:.1f}",
        "nMapDDSyn": fmt(ms["dd_LB"].get("Y", 0)),
        "pctMapDDSyn": f"{100*ms['dd_LB'].get('Y',0)/ms['dd_n']:.1f}",
        "nMapDDUnclear": fmt(ms["dd_LB"].get("U", 0)),
        "pctMapDDUnclear": f"{100*ms['dd_LB'].get('U',0)/ms['dd_n']:.1f}",
        "nMapDDCHN": fmt(ms["dd_SGCC"]),
        "nMapDDctyStated": fmt(ms["dd_cty_stated"]),
        "nMapBGD": fmt(ms["all_BGD"]),
        "nMapGov": fmt(ms["gov_n"]),
        "nMapGovMeasured": fmt(ms["gov_GOVM1"]),
        "nMapNoAbstract": fmt(ms["no_abstract"]),
        "nMapReviews": fmt(ms["by_code"].get("RV", 0)),
        "nPriorityFirm": fmt(sb["priority_firm"]),
        "nPriorityProbable": fmt(sb["priority_probable"]),
        "nPriorityUpper": fmt(sb["priority_total_upper"]),
        "nVenueExcluded": fmt((~pri.decision.str.startswith(("indexed", "probably"))).sum()),
        "nVenueProbable": fmt(pri.decision.str.startswith("probably").sum()),
        "nExtract": fmt(len(xv)),
        "nExtractConv": fmt((xv.numbers_supported == "yes (conversion)").sum()),
        "nSought": fmt(len(elig)),
        "nNotRetrieved": fmt((elig.has_pdf.astype(str) == "False").sum()),
        "pctRetrieved": f"{100*len(syn)/len(elig):.0f}",
        "nSyn": fmt(len(syn)),
        "nSynFirm": fmt((syn.priority == "firm").sum()),
        "nSynProbable": fmt((syn.priority == "probable").sum()),
        "nSynFT": fmt(syn.read_full.sum()),
        "pctSynFT": f"{100*syn.read_full.mean():.0f}",
    }
    lines = ["%% Generated by scripts/make_numbers.py -- do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (ROOT / "manuscript" / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
